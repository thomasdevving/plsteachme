import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const sources = [
 '20261030203000_restore_progress_sync.sql',
 '20261031100000_restore_coaching_sessions.sql',
 '20261031101000_restore_lesson_feedback.sql',
];
const sections = await Promise.all(sources.map(async name => {
 const sql = await readFile(new URL(`supabase/migrations/${name}`, root),'utf8');
 return `-- Source: ${name}\n${sql.replace(/^begin;\s*$/gmi,'').replace(/^commit;\s*$/gmi,'').replace(/^notify pgrst, 'reload schema';\s*$/gmi,'').trim()}`;
}));
await writeFile(new URL('supabase/repairs/learning-backend.sql',root),
 `-- Generated by node scripts/build-learning-repair.mjs. Do not edit this file directly.\n-- Run once in the Supabase project matching the Cloudflare Worker's SUPABASE_URL.\n-- Restores private progress, coaching and lesson feedback without resetting existing data.\nbegin;\n\n${sections.join('\n\n')}\n\nnotify pgrst, 'reload schema';\ncommit;\n`);
