// Embeds the share-image assets in lib/og-assets.ts, so /api/og needs no file system or network at runtime.
//   public/brand/og-coaches.png   the two 3D coaches (orange waves, green holds its magnifier), transparent
//   public/brand/og-mark.png      the hands mark, 144 px
//   public/fonts/og/*.ttf         DM Sans SemiBold and Lora, subset to Latin (the image renderer reads ttf, not woff2)
// Usage: node scripts/generate-og-assets.mjs
import { readFileSync, writeFileSync } from "node:fs";

const b64 = (path) => readFileSync(new URL(`../${path}`, import.meta.url)).toString("base64");
const out = `// Generated by scripts/generate-og-assets.mjs. Do not edit by hand.
export const OG_COACHES = "data:image/png;base64,${b64("public/brand/og-coaches.png")}";
export const OG_MARK = "data:image/png;base64,${b64("public/brand/og-mark.png")}";
export const OG_DM_SANS_SEMIBOLD = "${b64("public/fonts/og/dm-sans-semibold-latin.ttf")}";
export const OG_LORA = "${b64("public/fonts/og/lora-latin.ttf")}";
`;
writeFileSync(new URL("../lib/og-assets.ts", import.meta.url), out);
console.log(`lib/og-assets.ts: ${(out.length / 1024).toFixed(0)} KB`);
