import { writeFileSync } from "node:fs";
import { loadSkills } from "../lib/skills/loader";
const skills = loadSkills();
// Discover/validate files at build time, then bundle the small trial lookup.
// Workers must not scan lesson directories or read demo SVGs to start a session.
const trialCatalog = skills.map(skill => ({id:skill.id,status:skill.status,totalSteps:skill.steps.length}));
writeFileSync(new URL('../lib/skills/trial-catalog.generated.ts',import.meta.url),
  `// Generated by npm run validate:skills. Do not edit directly.\nexport const trialSkillCatalog: readonly {id:string;status:'available'|'coming_soon';totalSteps:number}[] = ${JSON.stringify(trialCatalog,null,2)};\n`);

console.info(`Validated ${skills.length} skills and their demo assets.`);
